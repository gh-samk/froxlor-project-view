<?php

namespace Froxlor\Ext\ProjectView;

use Froxlor\Database\Database;
use Froxlor\Settings;
use PDO;

/**
 * Gives Postfix and Dovecot the certificates of the mail. subdomains (SNI).
 *
 * Froxlor only puts the panel's certificate into the mail services
 * (AcmeSh::renewHookConfigs). Anyone who configures mail.customer.example as
 * their server would get a certificate warning. Both services can serve a
 * different certificate depending on the requested name; the files for that
 * are generated here from the certificates Froxlor stores in
 * domain_ssl_settings.
 *
 * Only what changed is applied (also after a renewal): a fingerprint per
 * service records which state was loaded last and which one failed last. A
 * failed state is retried at most hourly, so an error does not keep Postfix,
 * Dovecot and the log busy every minute.
 *
 * Froxlor's own entries (99-froxlor.ssl.conf, smtpd_tls_cert_file) stay
 * untouched: they keep serving the certificate for all other names. A service
 * is only touched if it is listed in Froxlor (system.le_renew_services) and its
 * configuration directory exists.
 *
 * Froxlor's own per-domain SNI: a future Froxlor release may ship native
 * per-domain mail SNI behind the setting mail.sni_enabled (upstream pull
 * request froxlor/froxlor#1423). As soon as that setting exists and is on,
 * this class stands down: it writes nothing and removes its own files, so the
 * two never serve competing local_name blocks or fight over
 * tls_server_sni_maps.
 *
 * teardown() works without Froxlor (no settings, no database), so the
 * uninstaller can call it after requiring only this file.
 */
class MailSni
{
	public const DEFAULTS = [
		'dir' => '/etc/ssl/froxlor-project-view-mail',
		'postfix_map' => '/etc/postfix/froxlor-project-view-sni',
		'dovecot_conf' => '/etc/dovecot/conf.d/98-froxlor-project-view-sni.conf',
		'postmap' => 'postmap -F',
		'postconf' => 'postconf',
		'postfix_reload' => 'postfix reload',
		'doveconf' => 'doveconf -n',
		'dovecot_reload' => 'systemctl reload dovecot',
	];

	/** A failed state is retried this often. */
	public const RETRY = 3600;

	private const HEADER = '# Generated by Froxlor Project View from the certificates of the mail. subdomains. Do not edit by hand.';

	/**
	 * Is Froxlor's own per-domain mail SNI switched on? Settings::Get returns
	 * null for settings that do not exist (Froxlor without that feature).
	 */
	public static function nativeSniActive(): bool
	{
		try {
			return (string)Settings::Get('mail.sni_enabled') === '1';
		} catch (\Throwable $e) {
			return false;
		}
	}

	/**
	 * Certificates of the mail. subdomains of e-mail domains. Any with their
	 * own certificate, whether the mail package or someone else created them.
	 */
	public static function certificates(): array
	{
		$stmt = Database::query("
			SELECT `s`.`domain` AS `host`, `z`.`ssl_cert_file`, `z`.`ssl_key_file`,
			       `z`.`ssl_cert_chainfile`, `z`.`ssl_fullchain_file`
			FROM `" . TABLE_PANEL_DOMAINS . "` `s`
			JOIN `" . TABLE_PANEL_DOMAINS . "` `p` ON `p`.`id` = `s`.`parentdomainid`
			JOIN `" . TABLE_PANEL_DOMAIN_SSL_SETTINGS . "` `z` ON `z`.`domainid` = `s`.`id`
			WHERE `s`.`domain` = CONCAT('mail.', `p`.`domain`)
			  AND `p`.`isemaildomain` = 1
			  AND `s`.`deactivated` = 0
			  AND `z`.`ssl_cert_file` <> ''
			  AND `z`.`ssl_key_file` <> ''
			ORDER BY `s`.`domain`
		");
		$list = [];
		foreach ($stmt->fetchAll(PDO::FETCH_ASSOC) as $row) {
			$chain = trim((string)$row['ssl_fullchain_file']) !== ''
				? trim((string)$row['ssl_fullchain_file'])
				: trim(trim((string)$row['ssl_cert_file']) . "\n" . trim((string)$row['ssl_cert_chainfile']));
			$list[] = [
				'host' => strtolower((string)$row['host']),
				'chain' => $chain . "\n",
				'key' => trim((string)$row['ssl_key_file']) . "\n",
			];
		}

		return $list;
	}

	/**
	 * Is the certificate good for the name? The whole chain is checked: every
	 * link must be readable and issued by the next one. A broken chain must
	 * never reach Postfix and Dovecot.
	 *
	 * The reasons go to the cron log.
	 *
	 * @return string|null null if it is; otherwise the reason
	 */
	public static function validate(array $c, int $now): ?string
	{
		if (!preg_match('/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/', $c['host'])) {
			return 'invalid name';
		}
		if (!preg_match_all('/-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----/s', $c['chain'], $blocks) || !$blocks[0]) {
			return 'certificate not readable';
		}
		$links = [];
		foreach ($blocks[0] as $block) {
			$info = @openssl_x509_parse($block);
			if ($info === false) {
				return 'certificate chain not readable';
			}
			$links[] = $info;
		}
		for ($i = 1; $i < count($links); $i++) {
			if (($links[$i - 1]['issuer'] ?? null) !== ($links[$i]['subject'] ?? false)) {
				return 'certificate chain does not fit together';
			}
		}
		if (!@openssl_x509_check_private_key($blocks[0][0], $c['key'])) {
			return 'key does not match the certificate';
		}
		if ((int)($links[0]['validTo_time_t'] ?? 0) <= $now) {
			return 'certificate expired';
		}
		$names = array_map(
			static fn($n) => strtolower(trim(substr(trim($n), 4))),
			array_filter(explode(',', (string)($links[0]['extensions']['subjectAltName'] ?? '')), static fn($n) => str_starts_with(trim($n), 'DNS:'))
		);
		if (!in_array($c['host'], $names, true)) {
			return 'certificate not valid for ' . $c['host'];
		}

		return null;
	}

	/** Postfix table for tls_server_sni_maps: name, key, chain. */
	public static function postfixMap(array $hosts, string $dir): string
	{
		$lines = [self::HEADER];
		foreach ($hosts as $host) {
			$lines[] = $host . ' ' . $dir . '/' . $host . '.key ' . $dir . '/' . $host . '.crt';
		}

		return implode("\n", $lines) . "\n";
	}

	/**
	 * Dovecot configuration with one local_name block per name.
	 *
	 * Dovecot 2.4 renamed the settings (ssl_cert/ssl_key became
	 * ssl_server_cert_file/ssl_server_key_file, without the "<" prefix); the
	 * local_name filter itself exists in both. Which syntax applies follows
	 * Froxlor's own choice in system.le_renew_services ("dovecot" or
	 * "dovecot24"), which also decides the syntax of Froxlor's
	 * 99-froxlor.ssl.conf. doveconf checks the result before any reload.
	 */
	public static function dovecotConf(array $hosts, string $dir, bool $dovecot24): string
	{
		$lines = [self::HEADER];
		foreach ($hosts as $host) {
			$lines[] = '';
			$lines[] = 'local_name ' . $host . ' {';
			if ($dovecot24) {
				$lines[] = '  ssl_server_cert_file = ' . $dir . '/' . $host . '.crt';
				$lines[] = '  ssl_server_key_file = ' . $dir . '/' . $host . '.key';
			} else {
				$lines[] = '  ssl_cert = <' . $dir . '/' . $host . '.crt';
				$lines[] = '  ssl_key = <' . $dir . '/' . $host . '.key';
			}
			$lines[] = '}';
		}

		return implode("\n", $lines) . "\n";
	}

	/**
	 * @param array $options overrides of DEFAULTS (paths, commands) — for tests
	 * @param array|null $certificates instead of the database — for tests
	 * @return array{hosts:int, skipped:array, postfix:string, dovecot:string, native:bool}
	 *         postfix/dovecot: unchanged | reloaded | removed | not set up | ERROR: …
	 */
	public static function run(array $options = [], ?array $certificates = null, ?int $now = null): array
	{
		$o = self::options($options);
		$now ??= time();

		if (self::nativeSniActive()) {
			return self::standDown($o, $now);
		}

		$certificates ??= self::certificates();
		$result = ['hosts' => 0, 'skipped' => [], 'postfix' => 'unchanged', 'dovecot' => 'unchanged', 'native' => false];

		$valid = [];
		foreach ($certificates as $c) {
			$reason = self::validate($c, $now);
			if ($reason === null) {
				$valid[$c['host']] = $c;
			} else {
				$result['skipped'][$c['host']] = $reason;
			}
		}
		ksort($valid);
		$hosts = array_keys($valid);
		$result['hosts'] = count($hosts);

		// As long as there is nothing to distribute and nothing was ever
		// distributed, the mail configuration stays completely untouched.
		if (!$valid && !is_file($o['postfix_map']) && !is_file($o['dovecot_conf'])) {
			return $result;
		}

		$stale = self::writeCertificates($valid, $o['dir']);
		$state = self::readState($o['state']);
		$certState = hash('sha256', json_encode($valid));

		$postfixOn = Settings::IsInList('system.le_renew_services', 'postfix') && is_dir(dirname($o['postfix_map']));
		$dovecot24 = Settings::IsInList('system.le_renew_services', 'dovecot24');
		$dovecotOn = ($dovecot24 || Settings::IsInList('system.le_renew_services', 'dovecot')) && is_dir(dirname($o['dovecot_conf']));

		if ($postfixOn) {
			$map = self::postfixMap($hosts, $o['dir']);
			$fingerprint = hash('sha256', $map . $certState);
			// If the .db is missing although Postfix loaded it, smtpd stops
			// accepting mail — then rebuild immediately. After a failure it is
			// missing anyway; then the hourly retry applies.
			$dbMissing = ($state['postfix']['ok'] ?? '') !== '' && !is_file($o['postfix_map'] . '.db');
			if ($dbMissing || self::due($state['postfix'] ?? [], $fingerprint, $now)) {
				self::write($o['postfix_map'], $map, 0600);
				$result['postfix'] = self::postfixApply($o);
				$state['postfix'] = self::remember($fingerprint, $result['postfix'], $now);
			}
		} elseif (is_file($o['postfix_map'])) {
			if (self::due($state['postfix'] ?? [], 'teardown', $now)) {
				$result['postfix'] = self::postfixTeardown($o);
				$state['postfix'] = str_starts_with($result['postfix'], 'ERROR')
					? ['ok' => '', 'failed' => 'teardown', 'failed_at' => $now]
					: [];
			}
		} else {
			$result['postfix'] = 'not set up';
		}

		if ($dovecotOn) {
			$conf = self::dovecotConf($hosts, $o['dir'], $dovecot24);
			$fingerprint = hash('sha256', $conf . $certState);
			if (self::due($state['dovecot'] ?? [], $fingerprint, $now)) {
				$before = is_file($o['dovecot_conf']) ? file_get_contents($o['dovecot_conf']) : null;
				self::write($o['dovecot_conf'], $conf, 0644);
				$result['dovecot'] = self::dovecotApply($o, $before);
				$state['dovecot'] = self::remember($fingerprint, $result['dovecot'], $now);
			}
		} elseif (is_file($o['dovecot_conf'])) {
			// Dropped from Froxlor's list: the file would otherwise still be
			// loaded but never maintained again, and soon point to deleted or
			// expired certificates.
			$result['dovecot'] = self::dovecotTeardown($o);
			$state['dovecot'] = [];
		} else {
			$result['dovecot'] = 'not set up';
		}

		// Old keys go only once both services have the new state: a restored
		// Dovecot file must never point to deleted files. As long as a file
		// lies around that nobody maintains, it might still point to old keys.
		$failed = str_starts_with($result['postfix'], 'ERROR') || str_starts_with($result['dovecot'], 'ERROR');
		$pending = ($postfixOn && ($state['postfix']['ok'] ?? '') === '') || ($dovecotOn && ($state['dovecot']['ok'] ?? '') === '')
			|| (!$postfixOn && is_file($o['postfix_map'])) || (!$dovecotOn && is_file($o['dovecot_conf']));
		if (!$failed && !$pending) {
			foreach ($stale as $file) {
				unlink($file);
			}
		}
		self::write($o['state'], json_encode($state) . "\n", 0600);

		return $result;
	}

	/**
	 * Removes everything this class set up: tls_server_sni_maps (only if it is
	 * exactly our table), the Postfix table, the Dovecot file, the keys and
	 * the state file. Must run as root.
	 *
	 * Works without Froxlor: no settings, no database. The Postfix table is
	 * only deleted once Postfix no longer refers to it — a missing table
	 * would stop smtpd from accepting mail. If tls_server_sni_maps still
	 * contains our table inside a value we do not own, nothing is overwritten;
	 * the table and the keys stay and the result says what to fix by hand.
	 *
	 * @param array $options overrides of DEFAULTS (paths, commands)
	 * @return array{postfix:string, dovecot:string, files:string}
	 *         each: removed | not set up | kept | ERROR: …
	 */
	public static function teardown(array $options = []): array
	{
		$o = self::options($options);
		$result = ['postfix' => 'not set up', 'dovecot' => 'not set up', 'files' => 'not set up'];

		if (is_file($o['postfix_map']) || is_file($o['postfix_map'] . '.db')) {
			$result['postfix'] = self::postfixTeardown($o);
		}
		if (is_file($o['dovecot_conf'])) {
			$result['dovecot'] = self::dovecotTeardown($o);
		}
		if (is_dir($o['dir'])) {
			if (str_starts_with($result['postfix'], 'ERROR')) {
				$result['files'] = 'kept';
			} else {
				foreach (glob($o['dir'] . '/*') ?: [] as $file) {
					if (is_file($file) || is_link($file)) {
						unlink($file);
					}
				}
				if (is_file($o['state'])) {
					unlink($o['state']);
				}
				$result['files'] = @rmdir($o['dir']) ? 'removed' : 'ERROR: could not remove ' . $o['dir'];
			}
		}

		return $result;
	}

	/**
	 * Froxlor's own SNI is on: write nothing, take down what is ours. A failed
	 * teardown is retried hourly like any other failed state.
	 */
	private static function standDown(array $o, int $now): array
	{
		$result = ['hosts' => 0, 'skipped' => [], 'postfix' => 'unchanged', 'dovecot' => 'unchanged', 'native' => true];
		if (!is_file($o['postfix_map']) && !is_file($o['postfix_map'] . '.db') && !is_file($o['dovecot_conf']) && !is_dir($o['dir'])) {
			$result['postfix'] = $result['dovecot'] = 'not set up';
			return $result;
		}
		$state = self::readState($o['state']);
		if (!self::due($state['teardown'] ?? [], 'teardown', $now)) {
			return $result;
		}
		$t = self::teardown($o);
		$result['postfix'] = $t['postfix'];
		$result['dovecot'] = $t['dovecot'];
		if (str_starts_with($t['postfix'], 'ERROR') || str_starts_with($t['dovecot'], 'ERROR') || str_starts_with($t['files'], 'ERROR')) {
			if (is_dir($o['dir'])) {
				$state['teardown'] = ['ok' => '', 'failed' => 'teardown', 'failed_at' => $now];
				self::write($o['state'], json_encode($state) . "\n", 0600);
			}
		}

		return $result;
	}

	private static function options(array $options): array
	{
		$o = array_merge(self::DEFAULTS, $options);
		$o['state'] ??= $o['dir'] . '/state.json';

		return $o;
	}

	/** Should this state be loaded? Not if it is already live or just failed. */
	private static function due(array $state, string $fingerprint, int $now): bool
	{
		if (($state['ok'] ?? '') === $fingerprint) {
			return false;
		}
		if (($state['failed'] ?? '') === $fingerprint && $now - (int)($state['failed_at'] ?? 0) < self::RETRY) {
			return false;
		}

		return true;
	}

	private static function remember(string $fingerprint, string $result, int $now): array
	{
		if (str_starts_with($result, 'ERROR')) {
			// Clear "ok": the loaded state is no longer the one in the file.
			return ['ok' => '', 'failed' => $fingerprint, 'failed_at' => $now];
		}

		return ['ok' => $fingerprint, 'failed' => '', 'failed_at' => 0];
	}

	private static function readState(string $file): array
	{
		$data = is_file($file) ? json_decode((string)file_get_contents($file), true) : null;

		return is_array($data) ? $data : [];
	}

	/**
	 * Writes keys and chains.
	 *
	 * @return array files that no longer belong to any name
	 */
	private static function writeCertificates(array $valid, string $dir): array
	{
		if (is_link($dir)) {
			throw new \RuntimeException('Refusing to use a symbolic link as key directory: ' . $dir);
		}
		if (!is_dir($dir)) {
			mkdir($dir, 0700, true);
		}
		chmod($dir, 0700);

		$wanted = [];
		foreach ($valid as $host => $c) {
			$wanted[] = $host . '.key';
			$wanted[] = $host . '.crt';
			self::write($dir . '/' . $host . '.key', $c['key'], 0600);
			self::write($dir . '/' . $host . '.crt', $c['chain'], 0644);
		}

		return array_values(array_filter(
			glob($dir . '/*.{key,crt}', GLOB_BRACE) ?: [],
			static fn($file) => !in_array(basename($file), $wanted, true)
		));
	}

	/**
	 * postmap -F stores the keys themselves (base64) in the .db. It must
	 * therefore be as tight as the key files: umask 077 and explicitly 0600.
	 * Postfix opens the table as root before dropping privileges.
	 *
	 * A tls_server_sni_maps value that is not ours is never overwritten.
	 */
	private static function postfixApply(array $o): string
	{
		$wanted = 'hash:' . $o['postfix_map'];
		[$code, $current] = self::command($o['postconf'] . ' -h tls_server_sni_maps');
		$current = trim($current);
		if ($code !== 0) {
			return 'ERROR: postconf: ' . $current;
		}
		if ($current !== '' && $current !== $wanted) {
			return 'ERROR: tls_server_sni_maps is already set to something else (' . $current . '), please merge by hand';
		}

		[$code, $output] = self::command('umask 077; ' . $o['postmap'] . ' ' . escapeshellarg($wanted));
		if ($code !== 0) {
			return 'ERROR: postmap: ' . $output;
		}
		if (is_file($o['postfix_map'] . '.db')) {
			chmod($o['postfix_map'] . '.db', 0600);
		}

		if ($current === '') {
			[$code, $output] = self::command($o['postconf'] . ' -e ' . escapeshellarg('tls_server_sni_maps=' . $wanted));
			if ($code !== 0) {
				return 'ERROR: postconf: ' . $output;
			}
		}

		[$code, $output] = self::command($o['postfix_reload']);

		return $code === 0 ? 'reloaded' : 'ERROR: postfix reload: ' . $output;
	}

	/**
	 * Postfix is no longer ours to configure: remove tls_server_sni_maps only
	 * if it is exactly our table, and delete the table only afterwards — a
	 * missing table would bring smtpd down.
	 */
	private static function postfixTeardown(array $o): string
	{
		$wanted = 'hash:' . $o['postfix_map'];
		[$code, $current] = self::command($o['postconf'] . ' -h tls_server_sni_maps');
		$current = trim($current);
		if ($code !== 0) {
			return 'ERROR: postconf: ' . $current;
		}
		if ($current === $wanted) {
			[$code, $output] = self::command($o['postconf'] . ' -X tls_server_sni_maps');
			if ($code !== 0) {
				return 'ERROR: postconf: ' . $output;
			}
			self::command($o['postfix_reload']);
		} elseif (str_contains($current, $o['postfix_map'])) {
			return 'ERROR: tls_server_sni_maps still contains the table (' . $current . '), please remove it by hand';
		}
		if (is_file($o['postfix_map'])) {
			unlink($o['postfix_map']);
		}
		if (is_file($o['postfix_map'] . '.db')) {
			unlink($o['postfix_map'] . '.db');
		}

		return 'removed';
	}

	private static function dovecotTeardown(array $o): string
	{
		unlink($o['dovecot_conf']);
		[$code, $output] = self::command($o['dovecot_reload']);

		return $code === 0 ? 'removed' : 'ERROR: dovecot reload: ' . $output;
	}

	/**
	 * Checks the new configuration with doveconf before Dovecot loads it. On
	 * an error the old file comes back — a broken block must never take down
	 * mail retrieval for all customers.
	 */
	private static function dovecotApply(array $o, ?string $before): string
	{
		[$code, $output] = self::command($o['doveconf']);
		if ($code !== 0) {
			if ($before === null) {
				unlink($o['dovecot_conf']);
			} else {
				self::write($o['dovecot_conf'], $before, 0644);
			}
			return 'ERROR: doveconf: ' . $output;
		}
		[$code, $output] = self::command($o['dovecot_reload']);

		return $code === 0 ? 'reloaded' : 'ERROR: dovecot reload: ' . $output;
	}

	/** Writes only if the content changed, atomically via a temporary file. */
	private static function write(string $file, string $content, int $mode): bool
	{
		if (is_file($file) && file_get_contents($file) === $content) {
			chmod($file, $mode);
			return false;
		}
		// Never write through a symbolic link: refuse a linked target, create
		// the temporary file exclusively ('x' fails on anything that already
		// exists, links included) and move it into place with rename(), which
		// replaces the directory entry instead of following it.
		if (is_link($file) || is_link(dirname($file))) {
			throw new \RuntimeException('Refusing to write through a symbolic link: ' . $file);
		}
		$tmp = $file . '.tmp' . getmypid();
		$old = umask(0077);
		try {
			$handle = @fopen($tmp, 'x');
			if ($handle === false || fwrite($handle, $content) !== strlen($content) || !fclose($handle)) {
				@unlink($tmp);
				throw new \RuntimeException('Cannot write ' . $file);
			}
		} finally {
			umask($old);
		}
		chmod($tmp, $mode);
		if (!rename($tmp, $file)) {
			@unlink($tmp);
			throw new \RuntimeException('Cannot write ' . $file);
		}

		return true;
	}

	/** @return array{0:int, 1:string} exit code and output on one line */
	private static function command(string $command): array
	{
		$output = [];
		exec($command . ' 2>&1', $output, $code);

		return [(int)$code, self::oneLine(implode(' ', $output))];
	}

	/**
	 * One line, at most 255 characters, without HTML. Same as
	 * SubdomainSsl::shorten(), duplicated so teardown() needs no other class.
	 */
	private static function oneLine(string $text): string
	{
		$text = trim(preg_replace('/\s+/u', ' ', strip_tags($text)) ?? '');

		return mb_substr($text, 0, 255);
	}
}
