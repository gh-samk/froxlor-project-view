<?php

/**
 * Checks migrations/connection.php without a database:
 *
 *   php tests/connection.php
 *
 * - userdata.inc.php is parsed, never executed (it belongs to the panel user,
 *   the helpers run as root).
 * - The DSN and the TLS options mirror Froxlor\Database\Database::getDB():
 *   socket vs host + port, $sql['ssl']['caFile'] / ['verifyServerCertificate'].
 */

if (PHP_SAPI !== 'cli') {
	http_response_code(404);
	exit(1);
}

require __DIR__ . '/../migrations/connection.php';

$failures = 0;
function check(bool $ok, string $text): void
{
	global $failures;
	printf("  %s %s\n", $ok ? 'OK    ' : 'FAILED', $text);
	if (!$ok) {
		$failures++;
	}
}

$dir = sys_get_temp_dir() . '/pv-connection-test-' . getmypid();
@mkdir($dir, 0700, true);
$write = static function (string $name, string $content) use ($dir): string {
	file_put_contents($dir . '/' . $name, $content);
	return $dir . '/' . $name;
};

echo "Format written by Froxlor 2.3 (PhpHelper::parseArrayToPhpFile)\n";
$file = $write('tls.php', <<<'PHP'
<?php
// autogenerated froxlor file

$sql = [
	'debug' => false,
	'host' => 'db.example.org',
	'port' => '3307',
	'user' => 'froxlor',
	'password' => <<<'EOT'
pa'ss"w$rd\n
EOT,
	'db' => 'froxlor',
	'ssl' => [
		'caFile' => '/etc/ssl/certs/db-ca.pem',
		'verifyServerCertificate' => true,
	],
];
$sql_root = [
	'0' => [
		'caption' => 'Default',
		'host' => 'db.example.org',
		'user' => 'root',
		'password' => <<<'EOT'
secret
EOT,
	],
];
PHP);
$vars = pv_read_userdata($file);
check(($vars['sql']['password'] ?? null) === 'pa\'ss"w$rd\n', 'nowdoc password is read literally');
check(($vars['sql_root'][0]['user'] ?? null) === 'root' || ($vars['sql_root']['0']['user'] ?? null) === 'root', 'nested sql_root is read');
$p = pv_connection_parameters($vars['sql']);
check($p['dsn'] === 'mysql:charset=utf8;dbname=froxlor;host=db.example.org;port=3307', 'TCP DSN with host and port: ' . $p['dsn']);
check(($p['options'][pv_pdo_mysql_attribute('SSL_CA')] ?? null) === '/etc/ssl/certs/db-ca.pem', 'TLS CA file from $sql[ssl][caFile]');
check(($p['options'][pv_pdo_mysql_attribute('SSL_VERIFY_SERVER_CERT')] ?? null) === true, 'server certificate verification from $sql[ssl][verifyServerCertificate]');

echo "Socket\n";
$file = $write('socket.php', "<?php\n\$sql = ['host' => 'localhost', 'socket' => '/run/mysqld/mysqld.sock', 'user' => 'froxlor', 'password' => 'x', 'db' => 'froxlor', 'ssl' => ['caFile' => '/ca.pem', 'verifyServerCertificate' => false]];\n");
$p = pv_connection_parameters(pv_read_userdata($file)['sql']);
check($p['dsn'] === 'mysql:charset=utf8;dbname=froxlor;unix_socket=/run/mysqld/mysqld.sock', 'socket DSN: ' . $p['dsn']);
check(!isset($p['options'][pv_pdo_mysql_attribute('SSL_CA')]), 'no TLS over a socket (as Froxlor)');

echo "Older line-by-line format and defaults\n";
$file = $write('old.php', "<?php\n\$sql['host'] = 'localhost';\n\$sql['user'] = \"froxlor\";\n\$sql['password'] = 'p\\'w';\n\$sql['db'] = 'froxlor';\n\$sql['debug'] = FALSE;\n");
$vars = pv_read_userdata($file);
check($vars['sql']['password'] === "p'w", 'escaped single quote');
$p = pv_connection_parameters($vars['sql']);
check($p['dsn'] === 'mysql:charset=utf8;dbname=froxlor;host=localhost;port=3306', 'default port 3306');
check(!isset($p['options'][pv_pdo_mysql_attribute('SSL_CA')]), 'no TLS without caFile');

echo "Code is refused, not executed\n";
$marker = $dir . '/executed';
foreach ([
	'call' => "<?php\n\$sql = ['user' => 'x', 'db' => 'y', 'password' => touch('$marker')];\n",
	'statement' => "<?php\ntouch('$marker');\n\$sql = ['user' => 'x', 'db' => 'y'];\n",
	'interpolation' => "<?php\n\$sql = ['user' => \"{\${touch('$marker')}}\", 'db' => 'y'];\n",
	'heredoc' => "<?php\n\$sql = ['user' => <<<EOT\n{\$x}\nEOT, 'db' => 'y'];\n",
] as $case => $code) {
	$file = $write("evil-$case.php", $code);
	$refused = false;
	try {
		pv_read_userdata($file);
	} catch (RuntimeException $e) {
		$refused = true;
	}
	check($refused && !file_exists($marker), "refused: $case");
}

array_map('unlink', glob($dir . '/*') ?: []);
@rmdir($dir);

echo $failures === 0 ? "\nAll checks passed.\n" : "\n$failures check(s) failed.\n";
exit($failures === 0 ? 0 : 1);
